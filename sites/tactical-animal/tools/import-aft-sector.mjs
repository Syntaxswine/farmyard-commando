import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';

// Reproducible, lossless packing of a pinned editor export. Never modify the
// inherited designer snapshot, and do not hand-edit the generated data module.
const root=path.resolve('sites/tactical-animal');
const relative='designer/a20b343a0234/tactics/sector-library/opening-checkpoint/foundation-1.json';
const bytes=fs.readFileSync(path.join(root,'dist',relative)),source=JSON.parse(bytes);
const {terrain,...metadata}=source,runs=[];
for(const row of terrain)for(const cell of row){const last=runs.at(-1);if(last?.[0]===cell)last[1]++;else runs.push([cell,1]);}
const provenance={source:relative,sourceCommit:'a20b343a0234b5d8b365a4e1668961ca1bf37653',sha256:createHash('sha256').update(bytes).digest('hex'),bytes:bytes.length};
const output='// Generated by tools/import-aft-sector.mjs from the pinned AFT editor export.\n'+
  `export const CHECKPOINT_PROVENANCE=${JSON.stringify(provenance)};\n`+
  `export const CHECKPOINT_DATA=${JSON.stringify({...metadata,terrainRLE:runs})};\n`;
const target=path.join(root,'dist','aft-checkpoint-data.js');
if(process.argv.includes('--check')){
  if(fs.readFileSync(target,'utf8').replaceAll('\r\n','\n')!==output)throw Error('Packed AFT sector is out of date.');
  console.log('Packed AFT checkpoint reproduces the pinned editor export.');
}else{fs.writeFileSync(target,output);console.log('Packed the original 240×240 AFT checkpoint without changing its tiles.');}
